import assert from 'node:assert/strict';
import { generateDungeon } from './generator-test-import.mjs';
const { emptyDungeon, editDungeon, playerDungeon, applyMap } = await import('../lib/dungeon.ts');
const { rememberScenery, sceneryKinds } = await import('../lib/scenery.ts');
const { remember } = await import('../lib/exploration.ts');
const { generationState } = await import('../lib/generation.ts');
const { initialGame } = await import('../lib/game.ts');
const base=editDungeon(emptyDungeon(),{tool:'room',from:[2,2],to:[8,8]});
const put=(map,x,y,extra={})=>editDungeon(map,{tool:'scenery',op:'save',kind:'crate',size:'medium',rotation:0,note:'SECRET SCENERY',hidden:false,expectedRevision:null,x,y,...extra});
let map=put(base,3,3), inside=map.scenery[0];map=put(map,1,3,{kind:'roots'});map=put(map,4,4,{hidden:true});
map.revealed=[...map.floors];
const publicMap=playerDungeon(map);
assert.equal(publicMap.scenery.length,2);
assert(publicMap.scenery.some(item=>item.x===1));
assert(!JSON.stringify(publicMap).includes('SECRET SCENERY'));
assert(publicMap.scenery.every(item=>!('hidden' in item)&&!('revision' in item)&&!('note' in item)));
assert.equal(playerDungeon({...map,revealed:[]}).scenery.length,0);
const level={map,memory:emptyDungeon(),visible:[],history:[],id:'ground',name:'Test'};
remember(level,['3,3','2,3']);
assert.equal(level.memory.scenery.length,2);
const memory=structuredClone(level.memory);
let moved=editDungeon(map,{tool:'scenery',op:'save',sceneryId:inside.id,expectedRevision:inside.revision,...inside,x:7,y:7,note:'NEW SECRET'});
assert.deepEqual(rememberScenery(memory,moved,new Set(['5,5'])),memory.scenery,'Unseen edits must not replace remembered scenery.');
level.map=moved;remember(level,['3,3']);
assert(!level.memory.scenery.some(item=>item.id===inside.id));
remember(level,['7,7']);
assert.equal(level.memory.scenery.find(item=>item.id===inside.id).x,7);
assert(!JSON.stringify(level.memory).includes('SECRET'));
assert.throws(()=>editDungeon(moved,{tool:'scenery',op:'remove',sceneryId:inside.id,expectedRevision:inside.revision}));
assert.throws(()=>put(base,3,3,{rotation:45}));
assert.throws(()=>put(base,56,3));
assert.throws(()=>put(base,3,3,{note:'x'.repeat(1001)}));
assert.throws(()=>put(map,3,3));
for(const kind of sceneryKinds){const item=put(base,4,4,{kind}).scenery[0];assert.equal(item.kind,kind);}
const game=initialGame('PJ','token');game.dungeon=base;
const command={tool:'scenery',op:'save',kind:'barrel',size:'small',rotation:90,x:4,y:4,expectedRevision:null,requestId:crypto.randomUUID()};
applyMap(game,command);applyMap(game,command);assert.equal(game.dungeon.scenery.length,1);
applyMap(game,{tool:'undo',requestId:crypto.randomUUID()});assert.deepEqual(game.dungeon,base);
// Undo must not make an old editor's revision valid for a different edit.
const editVersion=(source, previous, note)=>editDungeon(source,{tool:'scenery',op:'save',...previous,sceneryId:previous.id,expectedRevision:previous.revision,note});
const originalItem=map.scenery.find(item=>item.id===inside.id);
const versionB=editVersion(map,originalItem,'B');
const versionC=editVersion(map,originalItem,'C');
assert.notEqual(versionB.scenery.find(item=>item.id===inside.id).revision,versionC.scenery.find(item=>item.id===inside.id).revision);
assert.throws(()=>editVersion(versionC,versionB.scenery.find(item=>item.id===inside.id),'Stale B'));
const draft=generateDungeon({version:'v2',style:'castle',variant:0,name:'Scenery',levels:1,rooms:6,size:'small',corridors:'direct',connections:1,seed:'scenery'}).floors[0].map;
const [x,y]=draft.floors[0].split(',').map(Number), decorated=put(draft,x,y);
for(const field of ['floors','edges','generation','access','stairMarks'])assert.deepEqual(decorated[field],draft[field]);
const occupied=initialGame('PJ','token');occupied.dungeon=put(emptyDungeon(),1,1);
assert.equal(generationState(occupied).reuseEmpty,false);
console.log('PASS: community scenery kinds, public projection, outside adjacency, remembered hidden changes, stale edits, bounds, undo/replay, generator geometry and occupied-floor protection.');
