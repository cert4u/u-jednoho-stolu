import assert from 'node:assert/strict';
await import('./generator-test-import.mjs');
const {CatalogResolver,validateCatalog,pinContent}=await import('../lib/catalogs/resolver.ts');
const {builtinCatalog}=await import('../lib/catalogs/builtin.ts');
const {emptyEntries,sha256}=await import('../lib/catalogs/model.ts');
const make=id=>({manifest:{schemaVersion:1,id,name:id,author:'Autor',license:'CC0-1.0',description:'',version:'1.0.0',minAppVersion:'1.1.0',dependencies:[],fileLicenses:{}},entries:{...emptyEntries(),bestiary:[{...builtinCatalog.bundle.entries.bestiary[0],id:'rat',portrait:undefined}]},assets:[]});
const bundle=validateCatalog(make('doly')),other=validateCatalog(make('les'));
const installed=b=>({bundle:b,digest:'a'.repeat(64),kind:'local',enabled:true,revision:1});
const resolver=new CatalogResolver([installed(bundle),installed(other)]);
assert.equal(resolver.get('bestiary','doly:rat').catalogId,'doly');
assert.equal(resolver.get('bestiary','les:rat').catalogId,'les');assert(!resolver.get('bestiary','rat'));
assert.equal(resolver.get('bestiary','builtin:kobold').ref,'kobold');
assert(new CatalogResolver([{...installed(bundle),enabled:false}]).get('bestiary','doly:rat')===undefined);
const duplicate=make('doly');duplicate.entries.bestiary.push(duplicate.entries.bestiary[0]);assert.throws(()=>validateCatalog(duplicate),/Duplicitní/);
assert.throws(()=>validateCatalog({...make('doly'),manifest:{...bundle.manifest,id:'builtin'}}),/vyhrazené/);
assert.throws(()=>validateCatalog({...make('doly'),manifest:{...bundle.manifest,minAppVersion:'999.0.0'}}),/vyžaduje/);
const withAdventure=make('saga');withAdventure.entries.adventures=[{...builtinCatalog.bundle.entries.adventures[0],id:'tale',dungeonPreset:'builtin:castle',rooms:[{floor:1,role:'entrance',title:'Vchod',playerText:'Ticho',gmNotes:'Tajné',monsters:['rat']}]}];
assert.throws(()=>validateCatalog(withAdventure),/deklarovanou/);
withAdventure.manifest.dependencies=[{id:'builtin',minVersion:'1.1.0'}];
const saga=validateCatalog(withAdventure),sagaResolver=new CatalogResolver([installed(saga)]);
const pinned=await pinContent(undefined,sagaResolver,'adventures','saga:tale');
assert(pinned.entries.some(p=>p.type==='dungeon-presets'&&p.catalogId==='builtin'));
const restored=new CatalogResolver([],pinned);
assert.equal(restored.get('adventures','saga:tale').data.dungeonPreset,'castle','Explicit builtin links survive snapshot roundtrip.');
assert.equal(restored.get('bestiary','saga:rat').data.maxHp,saga.entries.bestiary[0].maxHp);
saga.entries.bestiary[0].maxHp=999;
const updated=new CatalogResolver([installed(saga)],pinned);
assert.notEqual(updated.get('bestiary','saga:rat').data.maxHp,999,'A catalog update must not mutate a pinned campaign template.');
assert.throws(()=>validateCatalog({...make('doly'),manifest:{...bundle.manifest,schemaVersion:99}}),/schemaVersion/);
assert.throws(()=>validateCatalog({...make('doly'),manifest:{...bundle.manifest,dependencies:[{id:'missing',minVersion:'1.0.0'}]}}),/Chybí závislost/);
assert.match(await sha256('catalog'),/^[a-f0-9]{64}$/);
console.log('PASS: catalog namespaces, builtin compatibility, versions/dependencies, duplicate rejection, adventure links and immutable portable campaign snapshots.');
